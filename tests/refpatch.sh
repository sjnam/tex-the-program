#!/bin/sh
# 기준 판의 tex.go에, 빠르기와 상관없는 수정 둘을 입힌다. 이 가지는 2026년 11월 14일에
# 입력 문자 256개를 모두 그대로 받게 하고(xchr) 메모리를 오백만 낱말로 늘렸는데, 기준 판
# (꼬리표 faithful)은 그렇지 않다. 그대로 견주면 제어 문자가 든 입력이나 메모리를 많이 쓰는
# 입력에서 늘 다르다고 나오므로, 기준 판도 같은 조건으로 만든다. 이미 고쳐진 판이면 그대로 둔다.
#
#   tests/refpatch.sh tex.go
#
# 필요한 것: perl
set -e
perl -0pi -e '
  s/(\n\tmemMax\s*=\s*)30000/${1}5000000/;
  s/(\n\tmemTop\s*=\s*)30000/${1}5000000/;
  s/(\n\tmaxHalfword\s*=\s*)65535/${1}8388607/;
  s/(\n\t+xchr\[i\] = )\x27 \x27/${1}textChar(i)/g;
' "$1"
